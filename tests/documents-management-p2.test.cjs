const {test} = require('node:test');
const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const path = require('node:path');
const mod = {exports:{}};
new Function('module','exports',ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/features/documents/domain/documentList.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(mod,mod.exports);
const {selectDocuments,normalizeDocumentSearch} = mod.exports;
const rows = Object.freeze([Object.freeze({id:'b',name:'إيصال ١٢.pdf',category:'receipt',createdAt:'2026-11-24T00:00:00Z'}),Object.freeze({id:'a',name:'Bank.pdf',category:'bank_statement',createdAt:'2026-11-23T00:00:00Z'})]);
const ids = (q='',c='all',s='newest') => selectDocuments(rows,q,c,s).map(x=>x.id);
test('Arabic normalization',()=>assert.equal(normalizeDocumentSearch('إِيـصال ۱۲'),'ايصال 12'));
test('Arabic search',()=>assert.deepEqual(ids('ايصال 12'),['b']));
test('English case insensitive',()=>assert.deepEqual(ids('BANK'),['a']));
test('Arabic category search',()=>assert.deepEqual(ids('كشف حساب'),['a']));
test('English category search',()=>assert.deepEqual(ids('receipt'),['b']));
test('category and query intersect',()=>assert.deepEqual(ids('bank','receipt'),[]));
test('oldest first',()=>assert.deepEqual(ids('','all','oldest'),['a','b']));
test('newest first',()=>assert.deepEqual(ids(),['b','a']));
test('name sort preserves records',()=>{assert.equal(ids('','all','name').length,2);assert.equal(rows[0].id,'b');});
test('empty query and no match',()=>{assert.deepEqual(ids('  '),['b','a']);assert.deepEqual(ids('missing'),[]);});
test('date search',()=>assert.deepEqual(ids('2026-11-23'),['a']));
